-- Stellar: Reddit Clone Schema
-- All tables use stl_ prefix to avoid conflicts with platform plt_ tables.

-- Communities (subreddits)
CREATE TABLE stl_communities (
    id                UUID         PRIMARY KEY,
    name              VARCHAR(50)  NOT NULL UNIQUE,
    display_name      VARCHAR(200) NOT NULL,
    description       TEXT         DEFAULT '',
    sidebar           TEXT         DEFAULT '',
    icon_url          VARCHAR(500),
    banner_url        VARCHAR(500),
    creator_id        UUID         NOT NULL,
    is_nsfw           BOOLEAN      NOT NULL DEFAULT FALSE,
    subscriber_count  BIGINT       NOT NULL DEFAULT 0,
    created_at        TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_stl_communities_name ON stl_communities(name);
CREATE INDEX idx_stl_communities_creator ON stl_communities(creator_id);
CREATE INDEX idx_stl_communities_subscribers ON stl_communities(subscriber_count DESC);

-- Community subscriptions
CREATE TABLE stl_subscriptions (
    user_id       UUID NOT NULL,
    community_id  UUID NOT NULL REFERENCES stl_communities(id) ON DELETE CASCADE,
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (user_id, community_id)
);
CREATE INDEX idx_stl_subscriptions_community ON stl_subscriptions(community_id);

-- Community members (moderators, admins)
CREATE TABLE stl_community_members (
    user_id       UUID        NOT NULL,
    community_id  UUID        NOT NULL REFERENCES stl_communities(id) ON DELETE CASCADE,
    role          VARCHAR(20) NOT NULL DEFAULT 'MEMBER',
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (user_id, community_id)
);

-- Community bans
CREATE TABLE stl_community_bans (
    user_id       UUID NOT NULL,
    community_id  UUID NOT NULL REFERENCES stl_communities(id) ON DELETE CASCADE,
    reason        TEXT,
    banned_by     UUID NOT NULL,
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (user_id, community_id)
);

-- Flairs
CREATE TABLE stl_flairs (
    id            UUID         PRIMARY KEY,
    community_id  UUID         NOT NULL REFERENCES stl_communities(id) ON DELETE CASCADE,
    name          VARCHAR(100) NOT NULL,
    color         VARCHAR(20)  NOT NULL DEFAULT '#666666',
    type          VARCHAR(10)  NOT NULL DEFAULT 'POST',
    UNIQUE (community_id, name, type)
);

-- Posts
CREATE TABLE stl_posts (
    id              UUID         PRIMARY KEY,
    community_id    UUID         NOT NULL REFERENCES stl_communities(id) ON DELETE CASCADE,
    author_id       UUID         NOT NULL,
    title           VARCHAR(300) NOT NULL,
    body            TEXT,
    url             VARCHAR(2000),
    image_url       VARCHAR(2000),
    post_type       VARCHAR(10)  NOT NULL DEFAULT 'TEXT',
    score           INT          NOT NULL DEFAULT 0,
    comment_count   INT          NOT NULL DEFAULT 0,
    flair_id        UUID         REFERENCES stl_flairs(id) ON DELETE SET NULL,
    is_locked       BOOLEAN      NOT NULL DEFAULT FALSE,
    is_pinned       BOOLEAN      NOT NULL DEFAULT FALSE,
    is_removed      BOOLEAN      NOT NULL DEFAULT FALSE,
    created_at      TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at      TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_stl_posts_community ON stl_posts(community_id, created_at DESC);
CREATE INDEX idx_stl_posts_author ON stl_posts(author_id, created_at DESC);
CREATE INDEX idx_stl_posts_score ON stl_posts(score DESC, created_at DESC);

-- Comments
CREATE TABLE stl_comments (
    id                UUID    PRIMARY KEY,
    post_id           UUID    NOT NULL REFERENCES stl_posts(id) ON DELETE CASCADE,
    author_id         UUID    NOT NULL,
    parent_comment_id UUID    REFERENCES stl_comments(id) ON DELETE CASCADE,
    body              TEXT    NOT NULL,
    score             INT     NOT NULL DEFAULT 0,
    depth             INT     NOT NULL DEFAULT 0,
    is_removed        BOOLEAN NOT NULL DEFAULT FALSE,
    created_at        TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at        TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_stl_comments_post ON stl_comments(post_id, created_at);
CREATE INDEX idx_stl_comments_author ON stl_comments(author_id, created_at DESC);
CREATE INDEX idx_stl_comments_parent ON stl_comments(parent_comment_id);

-- Votes (unified for posts and comments)
CREATE TABLE stl_votes (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     UUID        NOT NULL,
    target_id   UUID        NOT NULL,
    target_type VARCHAR(10) NOT NULL,
    value       SMALLINT    NOT NULL,
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (user_id, target_id, target_type)
);
CREATE INDEX idx_stl_votes_target ON stl_votes(target_id, target_type);

-- Saved items
CREATE TABLE stl_saved_items (
    user_id     UUID        NOT NULL,
    target_id   UUID        NOT NULL,
    target_type VARCHAR(10) NOT NULL,
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (user_id, target_id, target_type)
);

-- User flairs (per community)
CREATE TABLE stl_user_flairs (
    user_id      UUID NOT NULL,
    community_id UUID NOT NULL REFERENCES stl_communities(id) ON DELETE CASCADE,
    flair_id     UUID NOT NULL REFERENCES stl_flairs(id) ON DELETE CASCADE,
    PRIMARY KEY (user_id, community_id)
);

-- Reports
CREATE TABLE stl_reports (
    id          UUID         PRIMARY KEY,
    reporter_id UUID         NOT NULL,
    target_id   UUID         NOT NULL,
    target_type VARCHAR(10)  NOT NULL,
    reason      VARCHAR(500) NOT NULL,
    status      VARCHAR(20)  NOT NULL DEFAULT 'PENDING',
    resolved_by UUID,
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_stl_reports_status ON stl_reports(status);

-- User karma (materialized)
CREATE TABLE stl_user_karma (
    user_id       UUID PRIMARY KEY,
    post_karma    INT NOT NULL DEFAULT 0,
    comment_karma INT NOT NULL DEFAULT 0
);

-- Community rules
CREATE TABLE stl_community_rules (
    id           UUID         PRIMARY KEY,
    community_id UUID         NOT NULL REFERENCES stl_communities(id) ON DELETE CASCADE,
    title        VARCHAR(200) NOT NULL,
    description  TEXT         DEFAULT '',
    position     INT          NOT NULL DEFAULT 0
);
CREATE INDEX idx_stl_community_rules ON stl_community_rules(community_id, position);
